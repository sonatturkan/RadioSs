def dispatch_workflow(store: Store, principal: Principal, method: str,
                      path: str, body_loader: Callable[[], dict]) -> Any | None:
    """Call a public specialist service for an exact POST path, or return None."""
    match = re.fullmatch(r"/v1/workflows/([a-z-]+)/([a-z-]+)", path)
    if match is None:
        return None
    if method != "POST":
        raise StoreError("workflow actions require POST")
    action = ACTIONS.get(f"{match.group(1)}/{match.group(2)}")
    if action is None:
        return None
    body = body_loader()
    if any(key in body for key in ("store", "principal")) or any(
            isinstance(key, str) and key.startswith("_") for key in body):
        raise StoreError("workflow body contains reserved arguments")
    return action(store, principal, **body)
